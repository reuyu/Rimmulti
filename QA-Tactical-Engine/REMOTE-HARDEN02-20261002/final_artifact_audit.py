from pathlib import Path
from datetime import datetime, timezone
import hashlib
import json
import re
from PIL import Image

ROOT = Path(__file__).resolve().parent
REPORT = ROOT.parent.parent / 'QA_Remote_Tactical_Presentation_Hardening_02.md'


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest().upper()


def read_json(name):
    return json.loads((ROOT / name).read_text(encoding='utf-8-sig'))


identity = read_json('identity-before.json')
protected = read_json('production-before.json')
previous = read_json('integrity-after.json')
frozen = [dict(path=x['path'], expected=x['expected'], actual=sha(x['path'])) for x in identity]
for entry in frozen:
    entry['match'] = entry['expected'] == entry['actual']
protection = []
production_root = REPORT.parent / 'WarEconomyMod'
for entry in protected:
    path = Path(entry['path'])
    production = path.is_relative_to(production_root)
    protection.append(dict(path=str(path), expected=entry['before_current_qa'], actual=sha(path) if path.exists() else None, production=production, missing=not path.exists()))
for entry in protection:
    entry['match'] = entry['expected'] == entry['actual']
source_copies = []
for entry in previous['all_copied_candidate_source']:
    original = Path(entry['path'])
    relative = Path(*original.parts[original.parts.index('Source') + 1:])
    copy = ROOT / 'Reviewed' / 'Source' / relative
    source_copies.append(dict(path=str(original), copy=str(copy), match=sha(original) == sha(copy)))

text = REPORT.read_text(encoding='utf-8-sig')
links = re.findall(r'\]\((C:/[^)]+)\)', text)
missing_links = [link for link in links if not Path(link).exists()]
kana_count = len(re.findall(r'[\u3040-\u30ff]', text))
frames = {}
for name in ['graphical-load-errors.jpg', 'own-selected-before-draft.jpg', 'own-drafted.jpg', 'move-mirror-stalled-valid.jpg']:
    data = (ROOT / name).read_bytes()
    with Image.open(ROOT / name) as frame:
        width, height = frame.size
        frames[name] = dict(format=frame.format, width=width, height=height, bytes=len(data))

audit = dict(
    utc=datetime.now(timezone.utc).isoformat(),
    scope='Read-only final hash/link/artifact audit; no game process launch or candidate build',
    frozen=frozen,
    protected=protection,
    copied_source=source_copies,
    report_links_checked=len(links),
    missing_report_links=missing_links,
    unexpected_kana_count=kana_count,
    evidence_frame_metadata=frames,
)
assert all(x['match'] for x in frozen + source_copies + [x for x in protection if x['production']])
audit['nonproduction_reference_differences'] = [x for x in protection if not x['production'] and not x['match']]
assert not kana_count
# The two audit/manifest links are generated by this finalization itself.
assert all(Path(link).name in {'evidence-manifest.json', 'final-artifact-audit.json'} for link in missing_links)
(ROOT / 'final-artifact-audit.json').write_text(json.dumps(audit, ensure_ascii=False, indent=2), encoding='utf-8')

excluded = {'bin', 'obj', '__pycache__'}
files = []
for path in sorted(ROOT.rglob('*')):
    if not path.is_file() or path.name == 'evidence-manifest.json' or any(part in excluded for part in path.relative_to(ROOT).parts):
        continue
    files.append(dict(path=str(path), bytes=path.stat().st_size, sha256=sha(path)))
manifest = dict(
    utc=datetime.now(timezone.utc).isoformat(),
    report=dict(path=str(REPORT), bytes=REPORT.stat().st_size, sha256=sha(REPORT)),
    excluded_directory_names=sorted(excluded),
    evidence=files,
)
(ROOT / 'evidence-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps(dict(frozen=len(frozen), production=sum(x['production'] for x in protection), protected_matches=sum(x['match'] for x in protection), nonproduction_reference_differences=audit['nonproduction_reference_differences'], copied_source=len(source_copies), links=len(links), missing_links=len(missing_links), evidence_files=len(files), report_sha256=manifest['report']['sha256'], frames=frames), ensure_ascii=True))
